create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  first_name text not null default '',
  surname text not null default '',
  mode text not null default 'textbook',
  mode_variant text,
  language text not null default 'en',
  music boolean not null default false,
  visuals boolean not null default true,
  theme text not null default 'savanna',
  onboarded boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null check (char_length(content) <= 20000),
  style_label text,
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_user_created_at_idx
  on public.chat_messages (user_id, created_at);

alter table public.profiles enable row level security;
alter table public.chat_messages enable row level security;

drop policy if exists "Users can read their own profile" on public.profiles;
drop policy if exists "Users can create their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Users can read their own messages" on public.chat_messages;
drop policy if exists "Users can add their own messages" on public.chat_messages;
drop policy if exists "Users can delete their own messages" on public.chat_messages;

create policy "Users can read their own profile"
  on public.profiles for select to authenticated
  using (auth.uid() = id);
create policy "Users can create their own profile"
  on public.profiles for insert to authenticated
  with check (auth.uid() = id);
create policy "Users can update their own profile"
  on public.profiles for update to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

create policy "Users can read their own messages"
  on public.chat_messages for select to authenticated
  using (auth.uid() = user_id);
create policy "Users can add their own messages"
  on public.chat_messages for insert to authenticated
  with check (auth.uid() = user_id);
create policy "Users can delete their own messages"
  on public.chat_messages for delete to authenticated
  using (auth.uid() = user_id);

grant select, insert, update on public.profiles to authenticated;
grant select, insert, delete on public.chat_messages to authenticated;

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, first_name, surname)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'surname', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_user();
